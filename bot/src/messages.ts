export const EMPTY_LEADERBOARD =
  'Пока никто не доиграл до конца. Нажми «Играть» и стань первым.';

export function leaderboardMessage(entries: readonly Entry[]): string {
  if (entries.length === 0) return EMPTY_LEADERBOARD;

  const lines = entries.map(
    (entry, index) => `${index + 1}. <b>${escapeHtml(entry.name)}</b> — ${entry.score} / 100`,
  );
  return [
    `<b>Лучшие результаты (топ-${Math.min(TOP_SIZE, entries.length)})</b>`,
    '',
    ...lines,
    '',
    '<i>Список хранится в памяти бота и очищается при перезапуске.</i>',
  ].join('\n');
}

