export function getQuizResult(correctCount: number, total: number): QuizResult {
  const ratio = correctCount / total;
  if (ratio >= 0.85) {
    return {
      title: 'Эксперт по страхованию',
      message: 'Ты отлично разбираешься в теме! Можешь объяснять друзьям, как работает страхование.',
      icon: 'expert',
    };
  }
  if (ratio >= 0.6) {
    return {
      title: 'На верном пути',
      message: 'Хорошая база! Есть пара моментов, которые стоит повторить — посмотри раздел "Исследуй".',
      icon: 'good',
    };
  }
  return {
    title: 'Начало положено',
    message: 'Теперь ты знаешь больше, чем раньше! Попробуй пройти игру и вернись к квизу снова.',
    icon: 'beginner',
  };
}
